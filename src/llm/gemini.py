# =========================================================
# TIMESTAMP PARSING
# =========================================================

def _timestamp_to_seconds(value):
    """
    Convert:

        01:09
        05:30
        01:28:30

    into seconds.
    """

    if not value:
        return None

    parts = value.strip().split(":")

    try:

        if len(parts) == 2:

            minutes = int(parts[0])
            seconds = int(parts[1])

            return (
                minutes * 60
                + seconds
            )

        if len(parts) == 3:

            hours = int(parts[0])
            minutes = int(parts[1])
            seconds = int(parts[2])

            return (
                hours * 3600
                + minutes * 60
                + seconds
            )

    except ValueError:
        return None

    return None


# =========================================================
# EXTRACT TIMESTAMP FROM QUESTION
# =========================================================

def _extract_question_timestamp(question):
    """
    Detect timestamps from the user's question.

    Examples:

        At 01:09
        around 05:30
        at 1:28:30
        around 47 minutes
        at 1 hour 28 minutes
    """

    if not question:
        return None

    text = question.lower()

    # -----------------------------------------------------
    # HH:MM:SS
    # -----------------------------------------------------

    match = re.search(
        r"\b(\d{1,2}):(\d{2}):(\d{2})\b",
        text
    )

    if match:

        return (
            int(match.group(1)) * 3600
            + int(match.group(2)) * 60
            + int(match.group(3))
        )

    # -----------------------------------------------------
    # MM:SS
    # -----------------------------------------------------

    match = re.search(
        r"\b(\d{1,3}):(\d{2})\b",
        text
    )

    if match:

        return (
            int(match.group(1)) * 60
            + int(match.group(2))
        )

    # -----------------------------------------------------
    # HOURS + MINUTES
    # -----------------------------------------------------

    match = re.search(
        r"(\d+)\s*hour[s]?"
        r"(?:\s*(?:and\s*)?(\d+)\s*minute[s]?)?",
        text
    )

    if match:

        hours = int(
            match.group(1)
        )

        minutes = int(
            match.group(2) or 0
        )

        return (
            hours * 3600
            + minutes * 60
        )

    # -----------------------------------------------------
    # MINUTES
    # -----------------------------------------------------

    match = re.search(
        r"(\d+)\s*minute[s]?",
        text
    )

    if match:

        return (
            int(match.group(1)) * 60
        )

    return None


# =========================================================
# EXTRACT TIMESTAMPS FROM RETRIEVED CONTEXT
# =========================================================

def _extract_context_timestamps(context):
    """
    Extract timestamps generated by the YouTube
    retrieval context.

    Example:

        Timestamp: [01:09]
    """

    if not context:
        return []

    matches = re.findall(
        r"Timestamp:\s*\[([0-9:]+)\]",
        context,
        flags=re.IGNORECASE
    )

    timestamps = []

    for value in matches:

        seconds = _timestamp_to_seconds(
            value
        )

        if seconds is not None:

            timestamps.append(
                seconds
            )

    return timestamps


# =========================================================
# DETERMINE VIDEO CLIP
# =========================================================

def _determine_video_clip(
    question,
    context
):
    """
    Determine the smallest useful video region.

    Priority:

        1. Explicit timestamp in question.
        2. Retrieved transcript timestamps.
        3. Entire video.

    Timestamp questions use approximately ±45 seconds.

    Retrieved transcript questions use a compact region
    around the retrieved timestamps.
    """

    # =====================================================
    # 1. EXPLICIT USER TIMESTAMP
    # =====================================================

    question_timestamp = (
        _extract_question_timestamp(
            question
        )
    )

    if question_timestamp is not None:

        start = max(
            0,
            question_timestamp - 45
        )

        end = (
            question_timestamp + 45
        )

        return (
            start,
            end
        )


    # =====================================================
    # 2. RETRIEVED TRANSCRIPT TIMESTAMPS
    # =====================================================

    timestamps = (
        _extract_context_timestamps(
            context
        )
    )

    if timestamps:

        minimum = min(
            timestamps
        )

        maximum = max(
            timestamps
        )

        # Give the relevant transcript chunks
        # some surrounding visual/audio context.
        start = max(
            0,
            minimum - 30
        )

        end = (
            maximum + 30
        )

        # Never send an unnecessarily huge
        # multimodal window.
        if end - start > 180:

            center = (
                minimum + maximum
            ) / 2

            start = max(
                0,
                center - 90
            )

            end = (
                center + 90
            )

        return (
            start,
            end
        )


    # =====================================================
    # 3. NO TIMESTAMP
    # =====================================================

    return (
        None,
        None
    )


# =========================================================
# FORMAT SECONDS
# =========================================================

def _format_seconds(seconds):
    """
    Convert seconds to MM:SS / HH:MM:SS.
    """

    seconds = int(
        max(
            0,
            seconds
        )
    )

    hours = seconds // 3600

    minutes = (
        seconds % 3600
    ) // 60

    remaining = (
        seconds % 60
    )

    if hours > 0:

        return (
            f"{hours:02d}:"
            f"{minutes:02d}:"
            f"{remaining:02d}"
        )

    return (
        f"{minutes:02d}:"
        f"{remaining:02d}"
    )


# =========================================================
# YOUTUBE LEVEL-2 MULTIMODAL
# =========================================================

def generate_youtube_multimodal_response(
    video_url,
    context,
    question
):
    """
    Level-2 multimodal YouTube analysis.

    Uses Google's native YouTube video input.

    For timestamp-based questions, only the relevant
    video interval is processed.

    Gemini analyzes:

        - audio
        - visual frames
        - transcript context
        - slides
        - diagrams
        - equations
        - code
        - charts
        - demonstrations
    """

    # =====================================================
    # VALIDATE URL
    # =====================================================

    if not video_url:

        raise ValueError(
            "YouTube video URL is required "
            "for multimodal analysis."
        )


    # =====================================================
    # DETERMINE RELEVANT CLIP
    # =====================================================

    start_seconds, end_seconds = (
        _determine_video_clip(
            question=question,
            context=context
        )
    )


    # =====================================================
    # CREATE PROMPT
    # =====================================================

    if (
        start_seconds is not None
        and end_seconds is not None
    ):

        clip_description = f"""
The relevant video section is approximately:

START: {_format_seconds(start_seconds)}

END: {_format_seconds(end_seconds)}

Focus especially on this section.
"""

    else:

        clip_description = """
No specific timestamp was detected.

Use the available video content needed to answer
the question.
"""


    prompt = f"""
You are a precise multimodal YouTube RAG assistant.

You have access to the actual public YouTube video.

Analyze BOTH:

1. Spoken/audio content
2. Visual content

The retrieved transcript context is supporting evidence.

=========================================================
RELEVANT VIDEO SECTION
=========================================================

{clip_description}

=========================================================
STRICT RULES
=========================================================

1. Answer ONLY from the supplied YouTube video and
   retrieved transcript context.

2. Do not use outside knowledge.

3. Do not invent information.

4. For questions about what the speaker explains,
   use the spoken audio and transcript.

5. For questions about what is shown on screen,
   inspect the visual content.

6. Pay special attention to:

   - slides
   - diagrams
   - equations
   - graphs
   - charts
   - tables
   - code
   - demonstrations
   - written text

7. If the user asks about a timestamp, focus on that
   timestamp and nearby content.

8. Use timestamps in MM:SS format when useful.

9. Never invent timestamps.

10. Distinguish between:

    What the speaker says

    What is shown on screen

    What can be directly inferred from both

11. Give the direct answer first.

12. Then provide a concise explanation.

13. If the requested information is genuinely not
    present, say:

    "I couldn't find that information in the video."

=========================================================
RETRIEVED TRANSCRIPT CONTEXT
=========================================================

{context}

=========================================================
USER QUESTION
=========================================================

{question}

=========================================================
TASK
=========================================================

Analyze the relevant part of the YouTube video.

Use:

    AUDIO
    +
    VISUAL CONTENT
    +
    RETRIEVED TRANSCRIPT

If the question asks what is shown on screen,
describe what is actually visible.

If the question asks what the speaker explains,
use the spoken content.

If the question contains a timestamp, focus on that
specific point.

Answer the user now.
"""


    # =====================================================
    # BUILD VIDEO PART
    # =====================================================

    video_file_data = types.FileData(
        file_uri=video_url
    )


    # =====================================================
    # WITH CLIPPING
    # =====================================================

    if (
        start_seconds is not None
        and end_seconds is not None
    ):

        video_part = types.Part(
            file_data=video_file_data,

            video_metadata=types.VideoMetadata(
                start_offset=(
                    f"{int(start_seconds)}s"
                ),

                end_offset=(
                    f"{int(end_seconds)}s"
                ),

                # 1 FPS is the documented default
                # and is appropriate for this test.
                fps=1.0
            )
        )

    else:

        video_part = types.Part(
            file_data=video_file_data
        )


    # =====================================================
    # GENERATE RESPONSE
    # =====================================================

    response = client.models.generate_content(

        model=MULTIMODAL_MODEL_NAME,

        contents=types.Content(
            parts=[
                video_part,

                types.Part(
                    text=prompt
                )
            ]
        )
    )


    # =====================================================
    # EXTRACT ANSWER
    # =====================================================

    answer = response.text


    # =====================================================
    # VALIDATE ANSWER
    # =====================================================

    if not answer:

        raise RuntimeError(
            "Gemini returned an empty multimodal response."
        )


    return answer